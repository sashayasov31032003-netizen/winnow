"""Политика: какие процедуры разрешено запускать через API и ИИ.

Список закрытый намеренно. «Вычислить переменную» и «Перекодировать» считают
присланные извне выражения, а это другой уровень риска: выполнять чужой код на
сервере нельзя, пока выражения не проверены отдельно. Графики тоже исключены —
они возвращают не отчёт, а данные для рисования.

Модуль отдельный, чтобы этим списком пользовались и HTTP-слой, и инструменты
ИИ: два списка неминуемо разошлись бы, и агент получил бы доступ к тому, что
закрыто для обычного API.
"""

from __future__ import annotations

ALLOWED_PROCEDURES = frozenset(
    {
        "frequencies",
        "descriptives",
        "crosstabs",
        "ttest",
        "anova",
        "nonparametric",
        "correlations",
        "linear_regression",
        "logistic_regression",
        "reliability",
        "factor",
    }
)

__all__ = ["ALLOWED_PROCEDURES"]
